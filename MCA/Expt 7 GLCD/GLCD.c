/* Delay Function */

void delay()
{
    int i, j;

    for(i=0; i<50; i++)
        for(j=0; j<500; j++);
}


/* Send Data to GLCD */

void GLCD_data(unsigned char ch)
{
    IOCLR0 = 0xFF<<12;
    IOSET0 = ch<<12;
    IOSET1 = RS;
  //  IO1CLR = RW;
    IOSET1 = EN;
    delay();
    IOCLR1 = EN;
    delay();
}


/* Send Command to GLCD */

void GLCD_cmd(unsigned char ch)
{
    IOCLR0 = 0xFF<<12;
    IOSET0 = ch<<12;
    IOCLR1 = RS;
    //delay();
    IOSET1 = EN;
    delay();
    IOCLR1 = EN;
    delay();
}


/* GLCD Initialization */

void GLCD_init(void)
{
    PINSEL0 = 0;
    PINSEL1 = 0;
    PINSEL2 = 0;

    /* P0.12 to P0.19 as output */
    IODIR0 = 0xFF<<12;

    /* P1.20 to P1.25 as output */
    IODIR1 = 0x3F<<20;

    /* Reset GLCD */
    IOSET1 = GRST | CS1 | CS2 ;
    delay();
    IOCLR1 = RW | RS | EN;
    //delay();

    
    GLCD_cmd(0x3F);    /* Display ON */
    GLCD_cmd(0x40);    /* Column 0 */
    GLCD_cmd(0xB8);    /* Page 0 */
    
}
/* Display Image on GLCD */

void display(unsigned char *temp1)
{
    int i, j;

    for(i=0; i<8; i++)
    {
        /* First Half of GLCD */

        IOSET1 = CS1;
        IOCLR1 = CS2;

        GLCD_cmd(0xB8 | i);
        GLCD_cmd(0x40);

        for(j=0; j<64; j++)
             GLCD_data(temp1[(i*128)+j]);
        


        /* Second Half of GLCD */

        IO1CLR = CS1;
        IO1SET = CS2;

        GLCD_cmd(0xB8 | i);
        GLCD_cmd(0x40);

        for(j=64; j<128; j++)
              GLCD_data(temp1[(i*128)+j]);
        
    }
}
